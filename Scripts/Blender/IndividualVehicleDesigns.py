"""Individually authored silhouettes from the approved 20-vehicle sheet.

Each design is constructed and saved alone. Coordinates are metres, +Y forward.
Cabin outline runs from front sill up over the roof to the rear sill. Side panes
are explicit Y/Z polygons, rather than stretching the hatchback's window layout.
"""
from dataclasses import dataclass, field


@dataclass(frozen=True)
class VehicleDesign:
    identity: str
    family: str
    paint: tuple
    width: float
    length: float
    radius: float
    front_axle: float
    rear_axle: float
    belt: float
    nose: float
    cabin: tuple
    panes: tuple
    doors: tuple
    roof_half: float
    features: tuple = field(default_factory=tuple)

    @property
    def height(self):
        return max(z for y,z in self.cabin)

    @property
    def front(self):
        return self.length/2

    @property
    def rear(self):
        return -self.length/2

    def validate(self):
        if not self.rear<self.rear_axle<self.front_axle<self.front:
            raise ValueError('Axles outside the body: '+self.identity)
        if self.roof_half>=self.width/2 or self.belt<=self.radius*1.7:
            raise ValueError('Invalid cabin cross-section: '+self.identity)
        if len(self.cabin)<4 or not self.panes:
            raise ValueError('An individual cabin and window layout are required')


